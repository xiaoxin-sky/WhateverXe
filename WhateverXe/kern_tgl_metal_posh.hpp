static_assert(sizeof(dealloc) == 0xdc, "dealloc guard spans 0x7ecba..0x7ed96");
// 0x7ed87: jne 0x7ed96 skips operator delete for the only active buffer.
constexpr size_t branchOffset = 0xd87;
constexpr uint8_t branch[] {0x75,0x0d};
constexpr uint8_t release[] {0x90,0x90};

inline bool driver(const char *path) {
    if (!path) return false;
    // vn_getpath may expose the Data mount rather than its firmlink.
    constexpr const char data[] = "/System/Volumes/Data";
    if (!strncmp(path, data, sizeof(data)-1)) path += sizeof(data)-1;
    return !strcmp(path, "/Library/GPUBundles/AppleIntelTGLGraphicsMTLDriver.bundle/"
        "Contents/MacOS/AppleIntelTGLGraphicsMTLDriver");
}
// Cheap exact checks for every validated code page; the path is read only after.
inline bool candidate(uint64_t offset, const uint8_t *page) {
    return offset == pageOffset && page &&
        !memcmp(page + deallocOffset, dealloc, sizeof(dealloc));
}
inline void apply(uint8_t *page) {
    memcpy(page + branchOffset, release, sizeof(release));
}
// Lilu copies whole prologue instructions into its trampoline without
// relocation. Accept only push/mov-register/sub-rsp prologues covering the
// largest jump Lilu writes, or an earlier Lilu long/slotted route it chains.
// A short route (E9) cannot be shared and would make Lilu panic.
constexpr size_t routeSpan = 14;
inline bool routable(const uint8_t *code) {
    if (!code) return false;
    if (code[0] == 0xff && code[1] == 0x25) return true;
    size_t at = 0;
    while (at < routeSpan) {
        const uint8_t *i = code + at;
        if (i[0] >= 0x50 && i[0] <= 0x57) at += 1;
        else if (i[0] == 0x41 && i[1] >= 0x50 && i[1] <= 0x57) at += 2;
        else if ((i[0] & 0xf0) == 0x40 && i[1] == 0x89 && i[2] >= 0xc0) at += 3;
        else if (i[0] == 0x48 && i[1] == 0x83 && i[2] == 0xec) at += 4;
        else if (i[0] == 0x48 && i[1] == 0x81 && i[2] == 0xec) at += 7;
        else return false;
    }
    return true;
}

void processKernel(KernelPatcher &patcher);
